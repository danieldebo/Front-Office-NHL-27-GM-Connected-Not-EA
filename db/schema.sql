-- Matchup windows, not fixed clock times. Coordinating 32 humans across time
-- zones on exact times is the single most common reason leagues stall.
CREATE TABLE game (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    season_id       UUID NOT NULL REFERENCES season(id),
    week_number     INT,
    window_opens_at TIMESTAMPTZ NOT NULL,
    window_closes_at TIMESTAMPTZ NOT NULL,
    home_team_season_id UUID NOT NULL REFERENCES team_season(id),
    away_team_season_id UUID NOT NULL REFERENCES team_season(id),
    status          game_status NOT NULL DEFAULT 'scheduled',
    played_at       TIMESTAMPTZ,
    external_ids    JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (home_team_season_id <> away_team_season_id),
    CHECK (window_closes_at > window_opens_at)
);
CREATE INDEX ON game (season_id, window_closes_at);

-- Append-only. A corrected score is a NEW row that supersedes the old one, so
-- disputes and reversals stay visible in the record.
CREATE TABLE game_result (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    game_id         UUID NOT NULL REFERENCES game(id),
    home_goals      INT NOT NULL CHECK (home_goals >= 0),
    away_goals      INT NOT NULL CHECK (away_goals >= 0),
    decision        game_decision NOT NULL DEFAULT 'regulation',
    -- Provenance: this is the block that makes a future authoritative backfill
    -- a reconciliation instead of a rewrite.
    data_source     data_source NOT NULL DEFAULT 'manual',
    ingest_batch_id UUID,
    confidence      NUMERIC(4,3) CHECK (confidence BETWEEN 0 AND 1),
    reported_by     UUID REFERENCES app_user(id),
    verified_by     UUID REFERENCES app_user(id),
    verified_at     TIMESTAMPTZ,
    superseded_by   UUID REFERENCES game_result(id),
    supersede_reason TEXT,
    -- B4: optimistic-concurrency token for lifecycle transitions (confirm /
    -- dispute / supersede). The FACTS stay immutable; status and verified_by are
    -- lifecycle fields, and racing GMs must not resolve them last-write-wins.
    -- Surfaced as the ETag; state transitions require a matching If-Match.
    version         INT NOT NULL DEFAULT 1,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- H1: a regulation result can never be a tie, and an OT/SO result is decided
    -- by exactly one goal. Refused at write time, not merely reported nightly.
    CHECK (home_goals <> away_goals),
    CHECK (decision = 'regulation' OR ABS(home_goals - away_goals) = 1),
    -- A supersede must always state why. Silent edits are the failure mode this
    -- whole platform exists to eliminate.
    CHECK (superseded_by IS NULL OR supersede_reason IS NOT NULL)
);
CREATE INDEX ON game_result (game_id) WHERE superseded_by IS NULL;

