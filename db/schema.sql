CREATE TABLE league (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    slug            CITEXT UNIQUE NOT NULL,
    name            TEXT NOT NULL,
    visibility      league_visibility NOT NULL DEFAULT 'public',
    primary_color   TEXT,
