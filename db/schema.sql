-- Where a piece of data came from. Ordered loosely by authority, but authority
-- is resolved by data_source_authority below, not by enum order.
CREATE TYPE data_source AS ENUM (
    'manual',        -- typed by a human in the app
    'confirmed',     -- typed by one human, confirmed by the opposing human
    'ocr',           -- parsed from an uploaded screenshot
    'csv_import',    -- bulk import from a commissioner's spreadsheet
    'partner_api',   -- authoritative external feed (reserved for EA / partner)
    'system'         -- generated by the platform (auto-forfeit, sim, rollover)
);

CREATE TYPE seat_status       AS ENUM ('open', 'pending', 'filled', 'suspended', 'vacated');
CREATE TYPE game_status       AS ENUM ('scheduled', 'in_window', 'reported', 'confirmed', 'disputed', 'forfeited', 'postponed', 'simulated', 'voided');
CREATE TYPE game_decision     AS ENUM ('regulation', 'overtime', 'shootout');
CREATE TYPE txn_type          AS ENUM ('trade', 'signing', 'release', 'waiver_claim', 'call_up', 'send_down', 'ir_place', 'ir_activate', 'retire', 'draft_pick', 'reversal');
CREATE TYPE txn_status        AS ENUM ('proposed', 'accepted', 'pending_approval', 'approved', 'rejected', 'executed', 'reversed', 'withdrawn');
CREATE TYPE asset_kind        AS ENUM ('player', 'draft_pick', 'cap_space', 'retained_salary');
CREATE TYPE league_visibility AS ENUM ('public', 'unlisted', 'private');
CREATE TYPE member_role       AS ENUM ('owner', 'commissioner', 'assistant_commissioner', 'gm', 'spectator');

-- Authority ranking. Higher wins during reconciliation. Kept as a table rather
-- than baked into code so a future authoritative feed can be slotted in
