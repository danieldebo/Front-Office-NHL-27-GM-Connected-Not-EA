    external_ids    JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);

-- A season is scoped to one game title. This is what makes franchise history
-- survive the annual release cycle.
CREATE TABLE season (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    league_id           UUID NOT NULL REFERENCES league(id),
    ordinal             INT NOT NULL,                  -- 1, 2, 3... within the league
    label               TEXT NOT NULL,                 -- 'Season 1 (NHL 27)'
    game_title          TEXT NOT NULL,                 -- 'NHL27'
    starts_on           DATE,
    ends_on             DATE,
    salary_cap_cents    BIGINT,
    roster_min          INT,
    roster_max          INT,
    games_per_matchup   INT NOT NULL DEFAULT 1,
    points_win          INT NOT NULL DEFAULT 2,
    points_ot_loss      INT NOT NULL DEFAULT 1,
    points_reg_loss     INT NOT NULL DEFAULT 0,
    tiebreakers         TEXT[] NOT NULL DEFAULT ARRAY['points','row','wins','goal_diff','goals_for'],
    is_active           BOOLEAN NOT NULL DEFAULT true,
    external_ids        JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (league_id, ordinal)
);

-- Reference table of real NHL clubs. Kept separate so a franchise can change
-- which club it controls between seasons without losing its own history.
CREATE TABLE nhl_club (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    abbrev       TEXT UNIQUE NOT NULL,                 -- 'CHI'
    name         TEXT NOT NULL,                        -- 'Chicago Blackhawks'
    conference   TEXT,
    division     TEXT,
    external_ids JSONB NOT NULL DEFAULT '{}'::jsonb    -- { "nhl_api": "16", "ea": "..." }
);

-- THE CONTINUITY LAYER. A franchise persists across seasons and across game
-- titles. GMs come and go; the franchise keeps the banner.
CREATE TABLE franchise (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    league_id     UUID NOT NULL REFERENCES league(id),
    name          TEXT NOT NULL,
    founded_season_id UUID REFERENCES season(id),
    external_ids  JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ
);

-- One franchise's participation in one season, controlling one NHL club.
CREATE TABLE team_season (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    season_id     UUID NOT NULL REFERENCES season(id),
    franchise_id  UUID NOT NULL REFERENCES franchise(id),
    nhl_club_id   UUID REFERENCES nhl_club(id),
    conference    TEXT,
    division      TEXT,
    seat_status   seat_status NOT NULL DEFAULT 'open',
    external_ids  JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (season_id, franchise_id),
    UNIQUE (season_id, nhl_club_id)
);

-- Who is running that team, and when. Append a new row on replacement rather
-- than editing — a mid-season GM change is history, not a correction.
CREATE TABLE gm_assignment (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    team_season_id  UUID NOT NULL REFERENCES team_season(id),
    user_id         UUID NOT NULL REFERENCES app_user(id),
    role            member_role NOT NULL DEFAULT 'gm',
    started_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at        TIMESTAMPTZ,
    end_reason      TEXT                                -- 'resigned' | 'inactive' | 'removed' | 'season_end'
);
-- B3: preventive, not detective. At most one active GM per seat, enforced by
-- the database so two people can never both control (and report for) one
-- franchise between nightly data-quality runs.
CREATE UNIQUE INDEX gm_assignment_one_active
    ON gm_assignment (team_season_id) WHERE ended_at IS NULL;

CREATE TABLE league_membership (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    league_id   UUID NOT NULL REFERENCES league(id),
    user_id     UUID NOT NULL REFERENCES app_user(id),
    role        member_role NOT NULL DEFAULT 'gm',
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at     TIMESTAMPTZ,
    UNIQUE (league_id, user_id)
);

-- Bylaws as a versioned document. Traceable, diffable, citable in disputes.
CREATE TABLE rulebook_revision (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    league_id    UUID NOT NULL REFERENCES league(id),
    version      TEXT NOT NULL,                        -- '1.0', '1.1'
    body_md      TEXT NOT NULL,
    change_note  TEXT,
    authored_by  UUID NOT NULL REFERENCES app_user(id),
    effective_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (league_id, version)
);

