-- The export contract is defined before anyone asks for it. Bumping
-- export_schema_version is how a partner (EA or otherwise) knows the shape
-- changed. See front-office-data-model.md §6 for the payload spec.

CREATE TABLE export_manifest (
    id                    UUID PRIMARY KEY DEFAULT gen_random_uuid(),
