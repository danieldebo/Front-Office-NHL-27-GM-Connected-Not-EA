-- B1: idempotency store. Every mutating endpoint accepts an Idempotency-Key;
-- a replay within the window returns the stored response instead of acting
-- twice. This MUST be durable — mobile score submission on bad wifi is exactly
-- the retry case, and Replit restarts mean an in-memory cache is no cache.
-- Same key + different body is a client bug: return 422, never the cached body.
CREATE TABLE idempotency_key (
    user_id         UUID NOT NULL REFERENCES app_user(id),
    key             TEXT NOT NULL,
    request_digest  TEXT NOT NULL,             -- sha256(method + path + body)
    response_status INT,
    response_body   JSONB,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ NOT NULL DEFAULT now() + INTERVAL '24 hours',
    PRIMARY KEY (user_id, key)
);
CREATE INDEX ON idempotency_key (expires_at);   -- sweep expired rows

-- B2: transactional outbox. Side effects (Discord posts, outbound webhooks) are
-- written as rows in the SAME transaction as the business change, then drained
-- by a worker with at-least-once delivery and idempotent handlers. This is what
-- prevents announcing a trade that then rolled back. Present from day one so the
-- first notification uses the pattern instead of a direct in-request API call.
CREATE TABLE outbox (
    id              BIGSERIAL PRIMARY KEY,
    topic           TEXT NOT NULL,             -- 'result.confirmed', 'txn.executed', ...
    payload         JSONB NOT NULL,
    dedupe_key      UUID NOT NULL DEFAULT gen_random_uuid(),  -- consumer dedupe
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at    TIMESTAMPTZ,
    attempts        INT NOT NULL DEFAULT 0,
    last_error      TEXT,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ON outbox (next_attempt_at) WHERE processed_at IS NULL;

-- ---------------------------------------------------------------------------
-- Derived views — never stored, always computed
-- ---------------------------------------------------------------------------

-- Only current (non-superseded) results count toward the record.
CREATE VIEW v_active_result AS
SELECT r.*, g.season_id, g.home_team_season_id, g.away_team_season_id
FROM game_result r
JOIN game g ON g.id = r.game_id
WHERE r.superseded_by IS NULL
  AND g.status IN ('confirmed', 'forfeited', 'simulated');

-- One row per team per game, from that team's point of view.
CREATE VIEW v_team_game AS
SELECT season_id, home_team_season_id AS team_season_id, away_team_season_id AS opponent_team_season_id,
       home_goals AS goals_for, away_goals AS goals_against, decision, id AS result_id
FROM v_active_result
UNION ALL
SELECT season_id, away_team_season_id, home_team_season_id,
       away_goals, home_goals, decision, id
FROM v_active_result;

-- Standings. Recomputed on read, so a corrected result fixes the table for free.
CREATE VIEW v_standings AS
SELECT
    tg.season_id,
    tg.team_season_id,
    COUNT(*)                                                       AS gp,
    COUNT(*) FILTER (WHERE goals_for > goals_against)              AS w,
    COUNT(*) FILTER (WHERE goals_for < goals_against
                       AND decision = 'regulation')                AS l,
    COUNT(*) FILTER (WHERE goals_for < goals_against
                       AND decision <> 'regulation')               AS otl,
    COUNT(*) FILTER (WHERE goals_for > goals_against
                       AND decision <> 'shootout')                 AS row_wins,
    SUM(goals_for)                                                 AS gf,
    SUM(goals_against)                                             AS ga,
    SUM(goals_for) - SUM(goals_against)                            AS diff,
      COUNT(*) FILTER (WHERE goals_for > goals_against) * s.points_win
    + COUNT(*) FILTER (WHERE goals_for < goals_against
                         AND decision <> 'regulation') * s.points_ot_loss
    + COUNT(*) FILTER (WHERE goals_for < goals_against
                         AND decision = 'regulation') * s.points_reg_loss
                                                                   AS points
FROM v_team_game tg
JOIN season s ON s.id = tg.season_id
GROUP BY tg.season_id, tg.team_season_id, s.points_win, s.points_ot_loss, s.points_reg_loss;

-- Cap situation, derived from active contracts rather than stored per team.
CREATE VIEW v_cap_position AS
SELECT
    ts.id AS team_season_id,
    s.salary_cap_cents,
    COALESCE(SUM(c.cap_hit_cents), 0)                        AS cap_used_cents,
    s.salary_cap_cents - COALESCE(SUM(c.cap_hit_cents), 0)   AS cap_space_cents,
    COUNT(c.id)                                              AS roster_count,
    (COUNT(c.id) < s.roster_min OR COUNT(c.id) > s.roster_max
     OR COALESCE(SUM(c.cap_hit_cents), 0) > s.salary_cap_cents) AS is_illegal
FROM team_season ts
JOIN season s ON s.id = ts.season_id
LEFT JOIN contract c ON c.team_season_id = ts.id AND c.superseded_by IS NULL
GROUP BY ts.id, s.salary_cap_cents, s.roster_min, s.roster_max;

-- League health, used by the GM marketplace to rank open seats.
CREATE VIEW v_league_health AS
SELECT
    s.league_id,
    s.id AS season_id,
    COUNT(g.id)                                                        AS games_scheduled,
    COUNT(g.id) FILTER (WHERE g.status = 'confirmed')                  AS games_confirmed,
    COUNT(g.id) FILTER (WHERE g.status IN ('forfeited','postponed'))   AS games_missed,
    COUNT(DISTINCT ga.user_id) FILTER (WHERE ga.ended_at IS NULL)      AS active_gms,
    COUNT(DISTINCT ts.id) FILTER (WHERE ts.seat_status = 'open')       AS open_seats
FROM season s
LEFT JOIN game g ON g.season_id = s.id
LEFT JOIN team_season ts ON ts.season_id = s.id
LEFT JOIN gm_assignment ga ON ga.team_season_id = ts.id
GROUP BY s.league_id, s.id;

