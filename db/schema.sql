-- ============================================================================
-- Front Office — league platform schema
-- Target: PostgreSQL 15+
-- Schema version: 1.0.0
--
-- Design commitments (see front-office-data-model.md for rationale):
--   1. UUID primary keys; every mappable entity carries external_ids JSONB
--   2. Every fact carries provenance: source, ingest batch, confidence, verifier
--   3. Append-only event log; corrections supersede, they never overwrite
--   4. Derived values (standings, cap) are computed, never stored as editable state
--   5. Soft delete only (deleted_at); history stays legible forever
-- ============================================================================

